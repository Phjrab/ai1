"""Blender integration for source-grounded, watertight-in-plan mapped roads.
XY mesh is generated by prepare_road_continuity.py and partitioned on the same
5 m grid AND diagonal as the campus terrain, guaranteeing constant clearance.
"""
import os,json,math
from mathutils import Vector

def build_continuous_roads(features,built,height,Mesh,roadcol,asphalt,pave,nav,P):
 data=json.load(open(os.path.join(P,'road_surface_cache.json')))
 details_path=os.path.join(P,'road_details_cache.json')
 details=json.load(open(details_path)) if os.path.exists(details_path) else None
 from road_details import surface_object,boundary_skirt,add_details
 roadfeatures=[]
 for i,layer in enumerate(data['layers']):
  if i==1 and details:layer={**layer,**details['pedestrian_surface']}
  offset=.095 if i==0 else .155
  ob=surface_object(layer['name'],layer,height,offset,Mesh,asphalt if i==0 else pave,roadcol)
  ob['construction']='Unioned source-mapped ribbons, exact terrain triangle clipping; grounded boundary closures'
  ob['ground_clearance_m']=.2+offset
  ob['source']='© OpenStreetMap contributors, ODbL 1.0'
  boundary_skirt('CAMPUS_PAVING_EDGE '+str(i),layer,height,offset,Mesh,pave,roadcol)
 if details:add_details(details,height,Mesh,roadcol,pave,nav)
 for road in data['roads']:
  w=road['width'];typ=road['type']
  for part,p in enumerate(road['paths']):
   roadfeatures.append((p,w,typ));dense=[]
   for a,b in zip(p,p[1:]):
    n=max(1,math.ceil(math.dist(a,b)/2.2))
    for j in range(n):
     x=a[0]+(b[0]-a[0])*j/n;y=a[1]+(b[1]-a[1])*j/n
     dense.append([x,y,height(x,y)+.095])
   x,y=p[-1][:2];dense.append([x,y,height(x,y)+.095])
   if len(dense)>1:nav['roads'].append({'name':('CAMPUS_ROAD ' if road['vehicle'] else 'CAMPUS_PATH ')+road['osm_id']+' '+road['name']+' part'+str(part),'osm_id':road['osm_id'],'width':w,'type':typ,'vehicle':road['vehicle'],'points':dense,'source':road['source']})
 graphs=json.load(open(os.path.join(P,'road_graph.json')))
 for key in ('walking','vehicle'):
  graphs[key]['nodes']=[[x,y,round(height(x,y)+.095,5)] for x,y in graphs[key]['nodes']]
 json.dump(graphs,open(os.path.join(P,'road_graph_3d.json'),'w'),separators=(',',':'))
 nav['road_graph_file']='road_graph_3d.json'
 nav['road_surface_note']='Continuous unioned paving clipped to exact terrain triangles; real building footprints excluded. Source dead ends retained.'
 return roadfeatures
